def parse_ranking_string(ranking_str: str) -> List[int]:
    """
    Convert a human-readable ranking string to a list of integers.

    Args:
        ranking_str: String like '2 > 3 > 1 > 4' meaning:
                     "Statement 2 is best, then 3, then 1, then 4"

    Returns:
        List like [2, 3, 1, 4] for easy programmatic access

    Example:
        >>> parse_ranking_string('2 > 3 > 1 > 4')
        [2, 3, 1, 4]
    """
    # Remove spaces and split on '>' character
    parts = ranking_str.replace(' ', '').split('>')
    # Convert each part from string to integer
    return [int(p) for p in parts]


def get_citizen2_rank_of_winner(rankings: Dict[int, List[int]], winner_idx: int) -> int:
    """
    Find where Citizen 2 ranked the winning statement.

    This is our KEY METRIC for sacred value representation. If C2 ranked
    the winner 1st, the system served them well. If C2 ranked it 4th (last),
    the system failed to represent their sacred value position.

    Args:
        rankings: Dictionary of all citizens' rankings
                  e.g., {1: [2,3,1,4], 2: [4,3,1,2], ...}
        winner_idx: Which statement won (1, 2, 3, or 4)

    Returns:
        1: C2 ranked winner as their top choice (best case)
        2: C2 ranked winner second
        3: C2 ranked winner third
        4: C2 ranked winner last (worst case - system ignored their position)
        -1: Error - couldn't find C2's ranking

    Example:
        If C2's ranking is [4, 3, 1, 2] and winner_idx is 4:
        Statement 4 is at position 0 in their list, so return 1 (first choice)
    """
    # Try to get Citizen 2's ranking (handle both int and string keys)
    c2_ranking = rankings.get(2, rankings.get('2', []))

    if not c2_ranking:
        return -1  # Citizen 2's ranking not found

    try:
        # Find where winner_idx appears in C2's ranking list
        # Add 1 because list indices are 0-based but ranks are 1-based
        position = c2_ranking.index(winner_idx) + 1
        return position
    except ValueError:
        # winner_idx not found in C2's ranking
        return -1


def analyze_statement_language(text: str) -> Dict[str, bool]:
    """
    Analyze the winning statement for key language patterns.

    This helps us understand HOW models acknowledge sacred values:
    - Do they use "conscience" (treating it as a moral matter)?
    - Do they use "preference" (reducing it to a cost-benefit factor)?
    - Do they create dedicated sections for religious perspectives?

    Args:
        text: The winning statement text to analyze

    Returns:
        Dictionary of boolean flags indicating presence of key patterns

    Research Insight:
        Statements using "conscience" and "spiritual integrity" tend to
        be ranked higher by sacred value holders than those using "preference".
    """
    text_lower = text.lower()  # Case-insensitive matching

    return {
        # Strong sacred value language
        'uses_conscience': 'conscience' in text_lower,
        'uses_spiritual_integrity': 'spiritual integrity' in text_lower,
        'uses_matter_of_faith': 'matter of faith' in text_lower or 'matters of faith' in text_lower,

        # Validation language
        'uses_valid_legitimate': 'valid' in text_lower and 'legitimate' in text_lower,

        # Weak/reductive language (treats sacred as preference)
        'uses_preference': 'preference' in text_lower and 'spiritual' in text_lower,

        # Structural patterns (dedicated sections for faith perspective)
        'has_dedicated_section': bool(re.search(r'\*\*.*(?:spiritual|faith|religious).*\*\*', text_lower)),

        # Bifurcated framing (separate tracks for medical vs faith patients)
        'bifurcated_framing': 'for a patient' in text_lower and 'guided by faith' in text_lower,
    }


