def load_results_from_json(filepath: str) -> Optional[ModelResult]:
    """
    Load and parse a results JSON file from an experiment run.

    The Habermas Machine saves results in JSON format after each run.
    This function parses that format into our ModelResult structure.

    Args:
        filepath: Path to a results_*.json file

    Returns:
        ModelResult object with parsed data, or None if loading failed

    Expected JSON structure:
        {
            "model": "gemini-2.5-pro",
            "opinion_round": {
                "statements": [...],
                "rankings": {"citizen_1": "2 > 3 > 1 > 4", ...},
                "social_ranking": "2 > 3 > 1 > 4",
                "winner_index": 2,
                "winner_text": "..."
            },
            "critique_round": { ... similar ... },
            "template_retries": 0
        }
    """
    try:
        # Open and parse JSON file
        with open(filepath, 'r') as f:
            data = json.load(f)

        # Extract model name (fall back to filename if not in data)
        model_name = data.get('model', Path(filepath).stem)
        result = ModelResult(model_name=model_name)

        # Parse Opinion Round data if present
        if 'opinion_round' in data:
            op = data['opinion_round']

            # Convert rankings from string format to list format
            rankings = {}
            for k, v in op.get('rankings', {}).items():
                # Extract citizen number from key like 'citizen_1'
                citizen_id = int(k.replace('citizen_', ''))
                # Parse ranking string if needed
                rankings[citizen_id] = parse_ranking_string(v) if isinstance(v, str) else v

            winner_idx = op.get('winner_index', 1)

            # Create RoundResult object
            result.opinion_round = RoundResult(
                round_name='Opinion',
                statements=op.get('statements', []),
                rankings=rankings,
                social_ranking=parse_ranking_string(op.get('social_ranking', '')) if isinstance(op.get('social_ranking'), str) else op.get('social_ranking', []),
                winner_index=winner_idx,
                winner_text=op.get('winner_text', ''),
                citizen2_rank_of_winner=get_citizen2_rank_of_winner(rankings, winner_idx)
            )

        # Parse Critique Round data if present (same structure as Opinion)
        if 'critique_round' in data:
            cr = data['critique_round']

            rankings = {}
            for k, v in cr.get('rankings', {}).items():
                citizen_id = int(k.replace('citizen_', ''))
                rankings[citizen_id] = parse_ranking_string(v) if isinstance(v, str) else v

            winner_idx = cr.get('winner_index', 1)

            result.critique_round = RoundResult(
                round_name='Critique',
                statements=cr.get('statements', []),
                rankings=rankings,
                social_ranking=parse_ranking_string(cr.get('social_ranking', '')) if isinstance(cr.get('social_ranking'), str) else cr.get('social_ranking', []),
                winner_index=winner_idx,
                winner_text=cr.get('winner_text', ''),
                citizen2_rank_of_winner=get_citizen2_rank_of_winner(rankings, winner_idx)
            )

        # Get template retry count (technical reliability metric)
        result.template_retries = data.get('template_retries', 0)

        return result

    except Exception as e:
        print(f"Error loading {filepath}: {e}")
        return None


def load_results_from_manual_data() -> List[ModelResult]:
    """
    Load results from manually recorded experimental data.

    When JSON result files aren't available, we use data that was
    manually recorded during our conversation analysis. This captures
    the key findings from our experiments.

    This is a FALLBACK when automated result files aren't found.

    Returns:
        List of ModelResult objects with our experimental findings

    Data Format:
        (model_name, opinion_c2_rank, critique_c2_rank, template_retries)

        c2_rank meanings:
            1 = C2 ranked winner as their 1st choice (best outcome)
            2 = C2 ranked winner as their 2nd choice
            3 = C2 ranked winner as their 3rd choice
            4 = C2 ranked winner as their 4th choice (worst outcome)
            None = No data for this round
    """
    results = []

    # Our experimental findings from testing 6 different models
    # Each tuple: (model_name, opinion_round_c2_rank, critique_round_c2_rank, template_retries)
    experimental_data = [
        # Fast models - baseline performance
        ("gemini-2.0-flash", 3, None, 0),      # C2 ranked winner 3rd, no critique data
        ("gemini-2.0-flash-lite", 4, None, 0), # C2 ranked winner LAST (worst)

        # Thinking model - shows "rescue phenomenon"
        ("gemini-2.0-flash-thinking-exp", 4, 1, 4),  # 4th -> 1st! (rescued by critique)

        # Pro models - best overall
        ("gemini-2.5-pro", 1, 2, 0),           # C2 ranked winner 1st! (best initial)
        ("gemini-2.5-pro-preview-06-05", 3, 4, 0),  # 3rd -> 4th (critique made it worse)

        # Open source model
        ("gemma-3-27b-it", 3, None, 2),        # Middle tier, some template issues
    ]

    # Convert tuples to ModelResult objects
    for model_name, op_rank, cr_rank, retries in experimental_data:
        result = ModelResult(model_name=model_name, template_retries=retries)

        # Create Opinion Round result if we have data
        if op_rank is not None:
            result.opinion_round = RoundResult(
                round_name='Opinion',
                statements=[],           # We don't have full statement text
                rankings={},             # We don't have full ranking data
                social_ranking=[],
                winner_index=0,
                winner_text='',
                citizen2_rank_of_winner=op_rank  # This is our key metric
            )

        # Create Critique Round result if we have data
        if cr_rank is not None:
            result.critique_round = RoundResult(
                round_name='Critique',
                statements=[],
                rankings={},
                social_ranking=[],
                winner_index=0,
                winner_text='',
                citizen2_rank_of_winner=cr_rank
            )

        results.append(result)

    return results


