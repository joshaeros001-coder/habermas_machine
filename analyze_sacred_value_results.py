def plot_sacred_value_satisfaction(results: List[ModelResult], output_dir: str = '.'):
    """
    Figure 1: Bar chart showing how well each model serves the sacred value holder.

    This is the CORE METRIC of our research. For each model, we show:
    - Green bar: Citizen 2's ranking of winner in Opinion Round
    - Blue bar: Citizen 2's ranking of winner in Critique Round

    Lower bars are BETTER (C2 ranked winner higher).
    The red dashed line at 2.5 separates "acceptable" from "poor" outcomes.

    Args:
        results: List of ModelResult objects to visualize
        output_dir: Directory to save output files

    Outputs:
        - fig1_sacred_value_satisfaction.png (for slides)
        - fig1_sacred_value_satisfaction.pdf (for publication)
    """
    # Create figure with specific size (10 inches wide, 6 inches tall)
    fig, ax = plt.subplots(figsize=(10, 6))

    # Prepare data for plotting
    models = []          # Model names for x-axis labels
    opinion_ranks = []   # C2's ranking in Opinion Round
    critique_ranks = []  # C2's ranking in Critique Round

    for r in results:
        # Clean up model name for display (remove 'gemini-' prefix, add line breaks)
        models.append(r.model_name.replace('gemini-', '').replace('-', '\n'))

        # Extract C2 rankings (None if data not available)
        opinion_ranks.append(r.opinion_round.citizen2_rank_of_winner if r.opinion_round else None)
        critique_ranks.append(r.critique_round.citizen2_rank_of_winner if r.critique_round else None)

    # Set up x-axis positions for grouped bars
    x = np.arange(len(models))  # [0, 1, 2, 3, 4, 5] for 6 models
    width = 0.35                 # Width of each bar

    # Convert None values to 0 for plotting (we'll mark them as N/A)
    opinion_vals = [v if v else 0 for v in opinion_ranks]
    critique_vals = [v if v else 0 for v in critique_ranks]

    # Plot Opinion Round bars (green, positioned left of center)
    bars1 = ax.bar(x - width/2, opinion_vals, width,
                   label='Opinion Round',
                   color='#2ecc71',           # Green color
                   edgecolor='black',          # Black border
                   linewidth=0.5)              # Thin border

    # Plot Critique Round bars (blue, positioned right of center)
    bars2 = ax.bar(x + width/2, critique_vals, width,
                   label='Critique Round',
                   color='#3498db',           # Blue color
                   edgecolor='black',
                   linewidth=0.5)

    # Mark missing data with 'N/A' labels
    for i, (op, cr) in enumerate(zip(opinion_ranks, critique_ranks)):
        if op is None:
            ax.annotate('N/A', (x[i] - width/2, 0.2), ha='center', fontsize=8, color='gray')
        if cr is None:
            ax.annotate('N/A', (x[i] + width/2, 0.2), ha='center', fontsize=8, color='gray')

    # Configure axes and labels
    ax.set_xlabel('Model')
    ax.set_ylabel('Citizen 2 Rank of Winner\n(1=Best, 4=Worst)')
    ax.set_title('Sacred Value Holder\'s Satisfaction with Deliberation Outcome')
    ax.set_xticks(x)
    ax.set_xticklabels(models)
    ax.set_ylim(0, 5)                    # Y-axis from 0 to 5
    ax.set_yticks([1, 2, 3, 4])          # Only show ranks 1-4

    # Add reference line at 2.5 (threshold between acceptable and poor)
    ax.axhline(y=2.5, color='red', linestyle='--', alpha=0.5, label='Neutral threshold')

    # Add legend
    ax.legend(loc='upper right')

    # Add value labels on top of each bar
    for bar in bars1:
        if bar.get_height() > 0:
            ax.annotate(f'{int(bar.get_height())}',
                       xy=(bar.get_x() + bar.get_width()/2, bar.get_height()),
                       ha='center', va='bottom', fontsize=9)
    for bar in bars2:
        if bar.get_height() > 0:
            ax.annotate(f'{int(bar.get_height())}',
                       xy=(bar.get_x() + bar.get_width()/2, bar.get_height()),
                       ha='center', va='bottom', fontsize=9)

    # Save figure in both formats
    plt.tight_layout()  # Adjust spacing to prevent label cutoff
    plt.savefig(os.path.join(output_dir, 'fig1_sacred_value_satisfaction.png'))
    plt.savefig(os.path.join(output_dir, 'fig1_sacred_value_satisfaction.pdf'))
    print(f"Saved: fig1_sacred_value_satisfaction.png/pdf")
    plt.close()  # Close figure to free memory


def plot_deliberation_dynamics(results: List[ModelResult], output_dir: str = '.'):
    """
    Figure 2: Slope chart showing how the Critique Round affects C2.

    This is the MOST IMPACTFUL figure for presentations. It shows:
    - Green line going UP: Critique Round RESCUED the minority position
    - Red line going DOWN: Critique Round HURT the minority position

    The key insight: Deliberation can be a DOUBLE-EDGED SWORD for minorities.
    More rounds of deliberation don't guarantee better representation.

    Args:
        results: List of ModelResult objects
        output_dir: Directory to save outputs

    Outputs:
        - fig2_deliberation_dynamics.png
        - fig2_deliberation_dynamics.pdf
    """
    fig, ax = plt.subplots(figsize=(8, 6))

    # Only include models that have data for BOTH rounds
    complete_results = [r for r in results if r.opinion_round and r.critique_round]

    # Plot a line for each model
    for i, r in enumerate(complete_results):
        op_rank = r.opinion_round.citizen2_rank_of_winner   # Starting point (Opinion Round)
        cr_rank = r.critique_round.citizen2_rank_of_winner  # Ending point (Critique Round)

        # Choose color based on whether C2's outcome improved
        if cr_rank < op_rank:
            # Lower rank = better, so this is an IMPROVEMENT
            color = '#27ae60'  # Green
            label = 'Improved'
        elif cr_rank > op_rank:
            # Higher rank = worse, so this is a DEGRADATION
            color = '#e74c3c'  # Red
            label = 'Degraded'
        else:
            # No change
            color = '#95a5a6'  # Gray
            label = 'No change'

        # Plot line from Opinion Round (x=0) to Critique Round (x=1)
        ax.plot([0, 1], [op_rank, cr_rank], 'o-',  # 'o-' = circles with lines
                color=color,
                linewidth=2,
                markersize=10,
                alpha=0.8)

        # Add model name label at the end of the line
        model_short = r.model_name.replace('gemini-', '').replace('-exp', '')
        ax.annotate(model_short, (1.02, cr_rank), va='center', fontsize=9)

    # Configure axes
    ax.set_xlim(-0.1, 1.3)           # X-axis from -0.1 to 1.3 (room for labels)
    ax.set_ylim(0.5, 4.5)            # Y-axis from 0.5 to 4.5
    ax.set_xticks([0, 1])
    ax.set_xticklabels(['Opinion Round', 'Critique Round'])
    ax.set_yticks([1, 2, 3, 4])
    ax.set_yticklabels(['1st\n(Best)', '2nd', '3rd', '4th\n(Worst)'])
    ax.set_ylabel('Citizen 2\'s Ranking of Winning Statement')
    ax.set_title('Deliberation Dynamics: Does the Critique Round\nHelp or Hurt the Sacred Value Holder?')

    # IMPORTANT: Invert y-axis so "better" (rank 1) is at TOP
    ax.invert_yaxis()

    # Create custom legend
    improved_patch = mpatches.Patch(color='#27ae60', label='Improved (C2 better off)')
    degraded_patch = mpatches.Patch(color='#e74c3c', label='Degraded (C2 worse off)')
    ax.legend(handles=[improved_patch, degraded_patch], loc='lower right')

    # Save
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, 'fig2_deliberation_dynamics.png'))
    plt.savefig(os.path.join(output_dir, 'fig2_deliberation_dynamics.pdf'))
    print(f"Saved: fig2_deliberation_dynamics.png/pdf")
    plt.close()


def plot_technical_reliability(results: List[ModelResult], output_dir: str = '.'):
    """
    Figure 3: Horizontal bar chart of template compliance by model.

    The Habermas Machine requires models to output in a specific format:
        <answer>reasoning<sep>A > B > C > D</answer>

    Some models struggle with this format and need retries. This metric shows
    technical reliability - how well each model follows instructions.

    Color coding:
        - Green (0 retries): Perfect compliance
        - Orange (1-2 retries): Minor issues
        - Red (3+ retries): Major issues

    Args:
        results: List of ModelResult objects
        output_dir: Directory to save outputs
    """
    fig, ax = plt.subplots(figsize=(8, 5))

    # Prepare data
    models = [r.model_name.replace('gemini-', '').replace('-', '\n') for r in results]
    retries = [r.template_retries for r in results]

    # Color code by severity
    colors = []
    for r in retries:
        if r > 2:
            colors.append('#e74c3c')   # Red = major issues
        elif r > 0:
            colors.append('#f39c12')   # Orange = minor issues
        else:
            colors.append('#27ae60')   # Green = perfect

    # Create horizontal bar chart
    bars = ax.barh(models, retries, color=colors, edgecolor='black', linewidth=0.5)

    # Labels and title
    ax.set_xlabel('Template Retries (INCORRECT_TEMPLATE errors)')
    ax.set_title('Technical Reliability: Template Compliance by Model')
    ax.set_xlim(0, max(retries) + 1 if max(retries) > 0 else 5)

    # Add value labels at end of each bar
    for bar, val in zip(bars, retries):
        ax.annotate(f'{val}',
                   xy=(val + 0.1, bar.get_y() + bar.get_height()/2),
                   va='center', fontsize=10)

    # Create legend
    perfect = mpatches.Patch(color='#27ae60', label='Perfect (0 retries)')
    minor = mpatches.Patch(color='#f39c12', label='Minor issues (1-2 retries)')
    major = mpatches.Patch(color='#e74c3c', label='Major issues (3+ retries)')
