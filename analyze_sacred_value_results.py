@dataclass
class RoundResult:
    """
    Stores results from a single deliberation round (Opinion or Critique).

    In the Habermas Machine architecture:
    - Opinion Round: Citizens submit opinions, AI generates candidate statements,
                     citizens rank statements, Schulze voting selects winner
    - Critique Round: Citizens critique the winner, AI generates refined
                      statements, citizens rank again, Schulze selects refined winner

    Attributes:
        round_name: Either 'Opinion' or 'Critique'
        statements: List of 4 candidate statements generated by the AI
        rankings: Dictionary mapping citizen_id -> their ranking of statements
                  e.g., {1: [2,3,1,4]} means Citizen 1 ranked Statement 2 first
        social_ranking: The aggregated ranking from Schulze voting method
        winner_index: Which statement (1-4) won the vote
        winner_text: The full text of the winning statement
        citizen2_rank_of_winner: Where Citizen 2 (sacred value holder) ranked
                                 the winning statement. 1=they loved it, 4=they hated it
    """
    round_name: str                          # 'Opinion' or 'Critique'
    statements: List[str]                    # The 4 candidate statements
    rankings: Dict[int, List[int]]           # citizen_id -> [ranking list]
    social_ranking: List[int]                # Aggregated ranking from Schulze
    winner_index: int                        # Which statement won (1-4)
    winner_text: str                         # Full text of winner
    citizen2_rank_of_winner: int             # 1=best, 4=worst for C2


@dataclass
class ModelResult:
    """
    Complete results for testing one AI model.

    Each model is tested on the same sacred value scenario:
    - 5 citizens deliberating on SSRI medication for depression
    - Citizen 2 holds a sacred value (religious objection to medication)
    - Citizens 1, 3, 4, 5 hold secular cost-benefit perspectives

    Attributes:
        model_name: Name of the Gemini model tested (e.g., 'gemini-2.5-pro')
        opinion_round: Results from the first deliberation round
        critique_round: Results from the refinement round (may be None)
        template_retries: How many times the model failed to follow output format
    """
    model_name: str                              # e.g., 'gemini-2.5-pro'
    opinion_round: Optional[RoundResult] = None  # First round results
    critique_round: Optional[RoundResult] = None # Refinement round results
    template_retries: int = 0                    # Format compliance failures

    @property
    def critique_improved_c2(self) -> Optional[bool]:
        """
        Did the Critique Round improve Citizen 2's satisfaction?

        Returns:
            True: Critique Round made C2 happier (they ranked winner higher)
            False: Critique Round made C2 less happy
            None: Cannot determine (missing data for one or both rounds)

        Logic: Lower rank number = better. If critique rank < opinion rank,
               that means C2 ranked the Critique winner higher (improvement).
        """
        if self.opinion_round and self.critique_round:
            # Lower rank = better, so < means improvement
            return self.critique_round.citizen2_rank_of_winner < self.opinion_round.citizen2_rank_of_winner
        return None

    @property
    def c2_delta(self) -> Optional[int]:
        """
        Calculate the change in Citizen 2's satisfaction between rounds.

        Returns:
            Negative number: Improvement (e.g., -3 means went from 4th to 1st)
            Positive number: Degradation (e.g., +1 means went from 1st to 2nd)
            Zero: No change
            None: Cannot calculate (missing data)

        This is a key metric for the "rescue phenomenon" - when the Critique
        Round saves a minority position that was initially rejected.
        """
        if self.opinion_round and self.critique_round:
            return self.critique_round.citizen2_rank_of_winner - self.opinion_round.citizen2_rank_of_winner
        return None


